-- 1. สร้างตารางจัดเก็บการจองตัวละคร
create table if not exists public.rov_hero_claims (
  id bigint generated by default as identity primary key,
  room_id text not null default 'rov_webapp_sgyver_2026',
  hero_id text not null,
  student_name text not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 2. สร้าง Index ค้นหาตามห้อง
create index if not exists idx_rov_hero_claims_room on public.rov_hero_claims(room_id);

-- 3. เปิดใช้งาน Realtime สำหรับตารางนี้ (เพื่อให้โปรเจกเตอร์เด้งทันที)
alter publication supabase_realtime add table public.rov_hero_claims;

-- 4. ตั้งค่าสิทธิ์ความปลอดภัย (Row Level Security)
alter table public.rov_hero_claims enable row level security;

-- ลบนโยบายเดิมหากเคยมี (ป้องกัน error ซ้ำ)
drop policy if exists "Allow public read rov_hero_claims" on public.rov_hero_claims;
drop policy if exists "Allow public insert rov_hero_claims" on public.rov_hero_claims;
drop policy if exists "Allow public delete rov_hero_claims" on public.rov_hero_claims;

-- อนุญาตให้อ่านข้อมูลฮีโร่ที่เลือกได้ทุกคน
create policy "Allow public read rov_hero_claims"
  on public.rov_hero_claims for select
  using (true);

-- อนุญาตให้นักเรียนกดส่งชื่อและฮีโร่เข้ามาได้
create policy "Allow public insert rov_hero_claims"
  on public.rov_hero_claims for insert
  with check (true);

-- อนุญาตให้คุณครูกดรีเซ็ตห้องได้
create policy "Allow public delete rov_hero_claims"
  on public.rov_hero_claims for delete
  using (true);
